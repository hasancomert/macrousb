#!/usr/bin/env python3
"""Embed a web asset into a C header as a flash-resident byte array.

Usage:  embed.py <input-file> <output-header>

Generates:
    static const unsigned INDEX_HTML_LEN = <N>U;
    static const char INDEX_HTML[] = { 0x.., ... };

The Makefile runs this to turn web/index.html into firmware's web_content.h,
so editing the page and rebuilding is enough -- no manual conversion step.
"""
import sys
import os


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: embed.py <input> <output>\n")
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "rb") as f:
        data = f.read()

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    lines = []
    lines.append("/* Auto-generated by web/tools/embed.py -- do not edit. */")
    lines.append("#ifndef WEB_CONTENT_H_")
    lines.append("#define WEB_CONTENT_H_")
    lines.append("static const unsigned INDEX_HTML_LEN = %dU;" % len(data))
    lines.append("static const char INDEX_HTML[] = {")
    row = []
    for i, b in enumerate(data):
        row.append("0x%02x," % b)
        if len(row) == 16:
            lines.append("  " + "".join(row))
            row = []
    if row:
        lines.append("  " + "".join(row))
    lines.append("};")
    lines.append("#endif /* WEB_CONTENT_H_ */")
    with open(dst, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("embed.py: %s -> %s (%d bytes)" % (src, dst, len(data)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
